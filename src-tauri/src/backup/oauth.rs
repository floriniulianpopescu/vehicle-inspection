//! Google sign-in for desktop apps: system browser, loopback redirect and PKCE.

use std::time::Duration;

use base64::Engine;
use base64::engine::general_purpose::URL_SAFE_NO_PAD;
use serde::Deserialize;
use sha2::{Digest, Sha256};
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::TcpListener;
use tokio::sync::oneshot;

use crate::data::AppError;

/// Only files this app created. Google does not review apps limited to this scope.
const SCOPE: &str = "https://www.googleapis.com/auth/drive.file";
const SIGN_IN_LIMIT: Duration = Duration::from_secs(5 * 60);
const MAX_REQUEST_BYTES: usize = 8 * 1024;

const DONE_PAGE: &str = "<!doctype html><meta charset=utf-8><title>Inspecție Auto</title>\
<body style=\"font-family:sans-serif;text-align:center;margin-top:4rem\">\
<h1>Gata</h1><p>Poți închide această filă și reveni în aplicație.</p>\
<p>You can close this tab and return to the app.</p>";

/// Generated by build.rs from the file downloaded from Google Cloud, or `{}` when absent.
const CLIENT_FILE: &str = include_str!(concat!(env!("OUT_DIR"), "/google-oauth-client.json"));

#[cfg(debug_assertions)]
const FAKE_GOOGLE_VAR: &str = "VEHICLE_INSPECTION_FAKE_GOOGLE";

#[derive(Clone)]
pub struct GoogleApi {
    pub auth: String,
    pub token: String,
    pub drive: String,
    pub upload: String,
}

impl GoogleApi {
    pub fn current() -> Self {
        #[cfg(debug_assertions)]
        if let Ok(base) = std::env::var(FAKE_GOOGLE_VAR) {
            return Self {
                auth: format!("{base}/auth"),
                token: format!("{base}/token"),
                drive: format!("{base}/drive/v3"),
                upload: format!("{base}/upload/drive/v3"),
            };
        }
        Self {
            auth: "https://accounts.google.com/o/oauth2/v2/auth".into(),
            token: "https://oauth2.googleapis.com/token".into(),
            drive: "https://www.googleapis.com/drive/v3".into(),
            upload: "https://www.googleapis.com/upload/drive/v3".into(),
        }
    }
}

#[derive(Clone)]
pub struct OAuthClient {
    pub id: String,
    pub secret: Option<String>,
}

#[derive(Deserialize)]
struct ClientFile {
    installed: Option<InstalledClient>,
}

#[derive(Deserialize)]
struct InstalledClient {
    client_id: String,
    client_secret: Option<String>,
}

impl OAuthClient {
    fn parse(file: &str) -> Option<Self> {
        let installed = serde_json::from_str::<ClientFile>(file).ok()?.installed?;
        Some(Self { id: installed.client_id, secret: installed.client_secret })
    }

    pub fn load() -> Option<Self> {
        #[cfg(debug_assertions)]
        if std::env::var(FAKE_GOOGLE_VAR).is_ok() {
            return Some(Self { id: "fake-client".into(), secret: None });
        }
        Self::parse(CLIENT_FILE)
    }
}

pub struct Tokens {
    pub access: String,
    pub refresh: String,
}

#[derive(Deserialize)]
struct TokenResponse {
    access_token: String,
    refresh_token: Option<String>,
    scope: Option<String>,
}

fn random_token(bytes: usize) -> Result<String, AppError> {
    let mut buffer = vec![0u8; bytes];
    getrandom::fill(&mut buffer).map_err(|e| AppError::from_message(e.to_string()))?;
    Ok(URL_SAFE_NO_PAD.encode(buffer))
}

fn pkce_challenge(verifier: &str) -> String {
    URL_SAFE_NO_PAD.encode(Sha256::digest(verifier.as_bytes()))
}

#[derive(Debug, PartialEq)]
enum Callback {
    Code(String),
    Denied,
    /// Not Google's redirect, for example the browser asking for a favicon.
    Ignored,
}

fn parse_callback(request: &str, expected_state: &str) -> Callback {
    let target = request
        .lines()
        .next()
        .and_then(|line| line.strip_prefix("GET "))
        .and_then(|rest| rest.split(' ').next());
    let Some(query) = target.and_then(|target| target.strip_prefix("/?")) else {
        return Callback::Ignored;
    };

    let (mut state, mut code, mut error) = (None, None, false);
    for (key, value) in url::form_urlencoded::parse(query.as_bytes()) {
        match key.as_ref() {
            "state" => state = Some(value.into_owned()),
            "code" => code = Some(value.into_owned()),
            "error" => error = true,
            _ => {}
        }
    }

    if state.as_deref() != Some(expected_state) {
        Callback::Ignored
    } else if error {
        Callback::Denied
    } else {
        code.map_or(Callback::Ignored, Callback::Code)
    }
}

async fn wait_for_code(listener: &TcpListener, state: &str) -> Result<String, AppError> {
    loop {
        let Ok((mut stream, _)) = listener.accept().await else { continue };

        let mut request = Vec::new();
        let mut chunk = [0u8; 1024];
        while request.len() < MAX_REQUEST_BYTES && !request.windows(2).any(|pair| pair == b"\r\n") {
            match stream.read(&mut chunk).await {
                Ok(0) | Err(_) => break,
                Ok(count) => request.extend_from_slice(&chunk[..count]),
            }
        }

        let callback = parse_callback(&String::from_utf8_lossy(&request), state);
        let response = if callback == Callback::Ignored {
            "HTTP/1.1 404 Not Found\r\nContent-Length: 0\r\nConnection: close\r\n\r\n".to_string()
        } else {
            format!(
                "HTTP/1.1 200 OK\r\nContent-Type: text/html; charset=utf-8\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{DONE_PAGE}",
                DONE_PAGE.len()
            )
        };
        let _ = stream.write_all(response.as_bytes()).await;
        let _ = stream.shutdown().await;

        match callback {
            Callback::Code(code) => return Ok(code),
            Callback::Denied => return Err(AppError::code("sign_in_denied")),
            Callback::Ignored => {}
        }
    }
}

pub fn http_client() -> Result<reqwest::Client, AppError> {
    reqwest::Client::builder()
        .connect_timeout(Duration::from_secs(15))
        .timeout(Duration::from_secs(120))
        .build()
        .map_err(|e| AppError::from_message(e.to_string()))
}

pub fn offline(error: reqwest::Error) -> AppError {
    eprintln!("drive request failed: {error}");
    AppError::code("drive_offline")
}

async fn request_token(
    http: &reqwest::Client,
    api: &GoogleApi,
    client: &OAuthClient,
    fields: &[(&str, &str)],
) -> Result<TokenResponse, AppError> {
    let mut form = fields.to_vec();
    form.push(("client_id", &client.id));
    if let Some(secret) = &client.secret {
        form.push(("client_secret", secret));
    }

    let response = http.post(&api.token).form(&form).send().await.map_err(offline)?;
    let status = response.status();
    if status.is_success() {
        return response.json().await.map_err(offline);
    }
    // The body can echo request details, so only log the status.
    eprintln!("token request rejected: {status}");
    Err(AppError::code(if status.as_u16() == 400 || status.as_u16() == 401 {
        "drive_reauth"
    } else {
        "drive_error"
    }))
}

/// Opens the browser and waits for the user to finish signing in.
pub async fn authorize(
    api: &GoogleApi,
    client: &OAuthClient,
    open_browser: impl FnOnce(&str) -> Result<(), AppError>,
    cancel: oneshot::Receiver<()>,
) -> Result<Tokens, AppError> {
    let listener = TcpListener::bind(("127.0.0.1", 0))
        .await
        .map_err(|e| AppError::from_message(e.to_string()))?;
    let port = listener.local_addr().map_err(|e| AppError::from_message(e.to_string()))?.port();
    let redirect = format!("http://127.0.0.1:{port}");
    let verifier = random_token(48)?;
    let state = random_token(24)?;

    let mut url = url::Url::parse(&api.auth).map_err(|e| AppError::from_message(e.to_string()))?;
    url.query_pairs_mut()
        .append_pair("client_id", &client.id)
        .append_pair("redirect_uri", &redirect)
        .append_pair("response_type", "code")
        .append_pair("scope", SCOPE)
        .append_pair("state", &state)
        .append_pair("code_challenge", &pkce_challenge(&verifier))
        .append_pair("code_challenge_method", "S256")
        .append_pair("access_type", "offline")
        .append_pair("prompt", "consent");
    open_browser(url.as_str())?;

    let code = tokio::select! {
        code = wait_for_code(&listener, &state) => code?,
        _ = cancel => return Err(AppError::code("sign_in_cancelled")),
        _ = tokio::time::sleep(SIGN_IN_LIMIT) => return Err(AppError::code("sign_in_timeout")),
    };

    let http = http_client()?;
    let tokens = request_token(
        &http,
        api,
        client,
        &[
            ("grant_type", "authorization_code"),
            ("code", &code),
            ("code_verifier", &verifier),
            ("redirect_uri", &redirect),
        ],
    )
    .await?;

    // Google lets people untick individual permissions on the consent page.
    if tokens.scope.is_some_and(|scope| !scope.split(' ').any(|granted| granted == SCOPE)) {
        return Err(AppError::code("drive_permission_missing"));
    }
    let refresh = tokens.refresh_token.ok_or_else(|| AppError::code("drive_error"))?;
    Ok(Tokens { access: tokens.access_token, refresh })
}

pub async fn access_token(
    api: &GoogleApi,
    client: &OAuthClient,
    refresh_token: &str,
) -> Result<String, AppError> {
    let tokens = request_token(
        &http_client()?,
        api,
        client,
        &[("grant_type", "refresh_token"), ("refresh_token", refresh_token)],
    )
    .await?;
    Ok(tokens.access_token)
}

#[cfg(test)]
mod tests {
    use super::*;

    const LINE: &str = "GET /?state=abc&code=4%2F0Ad HTTP/1.1\r\nHost: 127.0.0.1\r\n";

    #[test]
    fn reads_the_code_from_the_redirect() {
        assert_eq!(parse_callback(LINE, "abc"), Callback::Code("4/0Ad".into()));
    }

    #[test]
    fn ignores_a_redirect_with_the_wrong_state() {
        assert_eq!(parse_callback(LINE, "other"), Callback::Ignored);
    }

    #[test]
    fn ignores_other_requests() {
        assert_eq!(parse_callback("GET /favicon.ico HTTP/1.1\r\n", "abc"), Callback::Ignored);
        assert_eq!(parse_callback("POST /?state=abc&code=x HTTP/1.1\r\n", "abc"), Callback::Ignored);
    }

    #[test]
    fn reports_a_refused_consent() {
        let line = "GET /?error=access_denied&state=abc HTTP/1.1\r\n";
        assert_eq!(parse_callback(line, "abc"), Callback::Denied);
    }

    #[test]
    fn pkce_matches_the_rfc_example() {
        assert_eq!(
            pkce_challenge("dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk"),
            "E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM"
        );
    }

    #[test]
    fn reads_the_file_google_provides() {
        let file = r#"{"installed":{"client_id":"id","client_secret":"secret","redirect_uris":["http://localhost"]}}"#;
        let client = OAuthClient::parse(file).unwrap();
        assert_eq!((client.id.as_str(), client.secret.as_deref()), ("id", Some("secret")));
        assert!(OAuthClient::parse("{}").is_none());
    }
}
